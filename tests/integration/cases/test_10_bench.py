# The bench itself (tests/integration/stand), checked before any case relies on it.
import re

import pytest

from conftest import DNS_MODE, sh
from helpers import ok


def test_client_veth_managed_and_connected():
    assert sh("nmcli -g GENERAL.STATE device show stand-cli").startswith("100")


def test_tunnel_dns_answers_root_zone():
    out = sh("ip netns exec stand dig +tries=1 +time=3 @203.0.113.1 . SOA")
    assert "status: NOERROR" in out and "ANSWER: 1" in out


def test_aaaa_only_name_resolves_to_ipv6_only():
    addrs = {line.split()[0] for line in sh("getent ahosts srv6.stand.test").splitlines()}
    assert addrs == {"2001:db8:100::1"}


def test_server_ipv6_and_lan_neighbour_reachable_without_tunnel():
    sh("ping -6 -c1 -W3 2001:db8:100::1")
    assert sh("curl -s -m 5 http://192.168.77.1/").strip() == "pnv stand: lan"


def test_internet_unreachable_without_tunnel():
    assert sh("curl -s -m 3 http://203.0.113.1/", check=False) == ""


def test_only_client_veth_has_default_routes():
    """And the emulated Wi-Fi, the second parent (IPv4 only), where the kernel has it (5.8)."""
    wifi = {"wlan0"} if ok("nmcli -g GENERAL.STATE connection show stand-wifi") else set()
    for family, expected in (("-4", {"stand-cli"} | wifi), ("-6", {"stand-cli"})):
        devs = set(re.findall(r"\bdev (\S+)", sh(f"ip {family} route show default")))
        assert devs == expected, family


def test_management_nic_up_without_ipv6():
    devs = [d for d, kind in (l.split(":") for l in sh("nmcli -t -f DEVICE,TYPE device").splitlines())
            if kind == "ethernet" and d != "stand-cli"]
    assert devs, "no management NIC"
    for dev in devs:
        assert "UP" in sh(f"ip -br link show {dev}")
        assert sh(f"ip -6 addr show dev {dev}").strip() == ""


@pytest.mark.skipif(DNS_MODE != "resolvconf", reason="resolv.conf mode only")
def test_resolv_conf_written_by_nm_with_isp_dns_only():
    conf = open("/etc/resolv.conf").read()
    assert conf.startswith("# Generated by NetworkManager")
    assert re.findall(r"^nameserver (\S+)", conf, re.M) == ["192.0.2.1"]


@pytest.mark.skipif(DNS_MODE != "resolved", reason="systemd-resolved mode only")
def test_resolved_in_use_with_isp_dns_only():
    assert "127.0.0.53" in open("/etc/resolv.conf").read()
    servers = set(re.findall(r"^\s*DNS Servers?: (.+)$", sh("resolvectl status"), re.M))
    assert servers == {"192.0.2.1"}


@pytest.mark.kvm
def test_wifi_emulation_available():
    """stand-up's wifi(): one hwsim radio is the access point in netns stand, the other the client under NM."""
    assert "wlan-srv" in sh("ip netns exec stand ip -br link")
    assert sh("nmcli -g GENERAL.STATE connection show stand-wifi").strip() == "activated"


@pytest.mark.kvm
def test_sleep_mode_is_deep():
    assert "[deep]" in open("/sys/power/mem_sleep").read()
